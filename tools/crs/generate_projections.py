"""Generate the coordinate systems the site upload can convert from.

Writes, for the app:
  src/data/projections.ts          EPSG code -> name, proj4 definition, NAD27 flag
  src/data/nad27Shift.ts           NAD27 -> NAD83 shift grid for the H-GAC area
  src/data/projections.fixture.json reference conversions for the tests

The set: every non-deprecated EPSG projected system for Texas and for UTM
zones 14N/15N on NAD83 (all realizations) or WGS 84, the NAD27 Texas and UTM
systems, Web Mercator, and the geographic NAD83/NAD27 systems. These cover
what Texas agencies export. Definitions come from PROJ via pyproj rather than
being typed by hand.

NAD27 needs a datum shift of 28-41 m across the region, which proj4js can only
apply with NOAA's grid files. Rather than ship the national grid, this samples
NOAA's NADCON grid (us_noaa_conus.tif, fetched from cdn.proj.org into PROJ's
user data directory) over the H-GAC area; the app interpolates it bilinearly.

Run from the repo root with the data-build environment (needs network once,
to fetch the grid):
    python tools/crs/generate_projections.py
"""

from __future__ import annotations

import json
import os
import urllib.request
import warnings
from pathlib import Path

import pyproj
from pyproj import CRS, Transformer
from pyproj.database import query_crs_info
from pyproj.enums import PJType

ROOT = Path(__file__).resolve().parents[2]
OUT_TS = ROOT / "src" / "data" / "projections.ts"
OUT_SHIFT = ROOT / "src" / "data" / "nad27Shift.ts"
OUT_FIXTURE = ROOT / "src" / "data" / "projections.fixture.json"

EXTRA = [3857, 4269, 4152, 4759, 6318]  # Web Mercator; NAD83, HARN, NSRS2007, 2011
NAD27 = [4267, 26714, 26715, 32037, 32038, 32039, 32040, 32041]

# Reference locations: downtown Houston, Huntsville (Walker County, the
# region's northern edge) and Bay City (Matagorda, its southern edge).
POINTS = [(-95.3698, 29.7604), (-95.5508, 30.7235), (-95.9697, 28.9828)]

# Shift grid: the H-GAC counties with a margin, every 0.1 degree.
GRID = {"west": -97.5, "south": 27.5, "east": -93.5, "north": 31.5, "step": 0.1}
SCALE = 1e7  # stored as integers of 1e-7 degree (about 1 cm)


def selected_codes() -> list[int]:
    rows = query_crs_info(auth_name="EPSG", pj_types=[PJType.PROJECTED_CRS])
    codes = {
        int(r.code)
        for r in rows
        if not r.deprecated
        and ("Texas" in r.name or "UTM zone 14N" in r.name or "UTM zone 15N" in r.name)
        and ("NAD83" in r.name or "WGS 84" in r.name)
        and "NAD83(CSRS)" not in r.name
        and "PA11" not in r.name
    }
    return sorted(codes | set(EXTRA) | set(NAD27))


def nad27_to_nad83() -> Transformer:
    grid = Path(pyproj.datadir.get_user_data_dir(True)) / "us_noaa_conus.tif"
    if not grid.exists():
        urllib.request.urlretrieve("https://cdn.proj.org/us_noaa_conus.tif", grid)
    t = Transformer.from_crs(4267, 4269, always_xy=True)
    if not t.accuracy or t.accuracy > 1:
        raise RuntimeError(f"NAD27->NAD83 is not using NOAA's grid (accuracy {t.accuracy} m)")
    return t


def main() -> None:
    shift = nad27_to_nad83()
    defs: dict[str, dict] = {}
    fixture: list[dict] = []
    for code in selected_codes():
        crs = CRS.from_epsg(code)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")  # to_proj4 warns that PROJ strings drop metadata
            proj4 = crs.to_proj4()
        nad27 = code in NAD27
        if nad27:
            # proj4js cannot apply the NAD27 datum shift without NOAA's grid
            # files, so the app projects on the Clarke 1866 ellipsoid alone and
            # applies the shift itself from nad27Shift.ts.
            proj4 = proj4.replace("+datum=NAD27", "+ellps=clrk66")
        defs[str(code)] = {"name": crs.name, "proj4": proj4, "nad27": nad27}

        # Reference conversions. For NAD27 the expected answer is the NAD83
        # position (through NOAA's grid), testing projection and shift together;
        # otherwise the system's own geographic coordinates, isolating the
        # projection math.
        if nad27:
            to_src = Transformer.from_crs(4269, crs, always_xy=True)
        else:
            to_src = Transformer.from_crs(crs.geodetic_crs, crs, always_xy=True)
        for lon, lat in POINTS:
            x, y = to_src.transform(lon, lat)
            fixture.append({"code": code, "nad27": nad27, "lon": lon, "lat": lat, "x": x, "y": y})

    lines = [
        "// GENERATED by tools/crs/generate_projections.py from PROJ (pyproj). Do not edit.",
        "// Coordinate systems a site upload can be converted from: EPSG code ->",
        "// name, proj4 definition, and whether it is on the NAD27 datum (whose",
        "// shift the app applies from nad27Shift.ts). See services/parseUploadedFile.ts.",
        "",
        "export const PROJECTIONS: Record<string, { name: string; proj4: string; nad27: boolean }> = {",
    ]
    for code, d in defs.items():
        lines.append(
            f"  '{code}': {{ name: {json.dumps(d['name'])}, proj4: {json.dumps(d['proj4'])}, nad27: {str(d['nad27']).lower()} }},"
        )
    lines.append("}")
    OUT_TS.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Shift grid: NAD83 minus NAD27, rows south to north, columns west to east.
    cols = round((GRID["east"] - GRID["west"]) / GRID["step"]) + 1
    rows = round((GRID["north"] - GRID["south"]) / GRID["step"]) + 1
    dlon: list[int] = []
    dlat: list[int] = []
    for r in range(rows):
        lat = GRID["south"] + r * GRID["step"]
        for c in range(cols):
            lon = GRID["west"] + c * GRID["step"]
            x, y = shift.transform(lon, lat)
            dlon.append(round((x - lon) * SCALE))
            dlat.append(round((y - lat) * SCALE))
    shift_lines = [
        "// GENERATED by tools/crs/generate_projections.py from NOAA's NADCON grid",
        "// (us_noaa_conus.tif, via PROJ). Do not edit.",
        "// NAD27 -> NAD83 shift over the H-GAC area: NAD83 minus NAD27, in units of",
        "// 1e-7 degree, on a regular grid, rows south to north, columns west to east.",
        "",
        f"export const NAD27_SHIFT = {{",
        f"  west: {GRID['west']}, south: {GRID['south']}, step: {GRID['step']}, cols: {cols}, rows: {rows}, scale: {SCALE:.0f},",
        f"  dlon: {json.dumps(dlon, separators=(',', ':'))},",
        f"  dlat: {json.dumps(dlat, separators=(',', ':'))},",
        "}",
    ]
    OUT_SHIFT.write_text("\n".join(shift_lines) + "\n", encoding="utf-8")
    OUT_FIXTURE.write_text(json.dumps(fixture, indent=1) + "\n", encoding="utf-8")
    print(f"{len(defs)} coordinate systems -> {OUT_TS.relative_to(ROOT)}")
    print(f"NAD27 shift grid {cols}x{rows} -> {OUT_SHIFT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
